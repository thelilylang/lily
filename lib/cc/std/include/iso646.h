/*
 * ISO C99 Standard: 7.9 Alternative spellings <iso646.h>
 */

#ifndef _CC_STD_ISO646_H
#define _CC_STD_ISO646_H

/* The operators the standard gives another spelling to, for a source character
   set that has no way of writing the punctuation they are written with. */

#define and &&
#define and_eq &=
#define bitand &
#define bitor |
#define compl ~
#define not !
#define not_eq !=
#define or ||
#define or_eq |=
#define xor ^
#define xor_eq ^=

#endif /* _CC_STD_ISO646_H */
